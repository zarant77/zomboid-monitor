  assert.equal((await r(2, `/api/faction-invites/${token}`)).faction.name, 'Перша');
  assert.equal((await r(2, `/api/faction-invites/${token}/accept`, 'POST')).status, 200);
  await r(1, `/api/factions/${a.id}/invites`, 'POST', { enabled: false });
  assert.equal((await r(3, `/api/faction-invites/${token}/accept`, 'POST')).status, 404);
  assert.equal((await r(2, `/api/factions/${a.id}/invites`, 'POST', { enabled: true })).status, 403);
  const item = { name: 'Модова книжка', category: 'book', quantity: 2 };
  assert.equal((await r(2, `/api/factions/${a.id}/items/Custom.Book`, 'PUT', item)).status, 200);
