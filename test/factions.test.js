test('joining another faction switches membership atomically without moving inventory', async t => {
  const { db, request: r } = setup(t);
  const a = (await r(1, '/api/factions', 'POST', { name: 'A' })).faction;
  const b = (await r(3, '/api/factions', 'POST', { name: 'B' })).faction;
  async function join(user, faction) {
    const i = (await r(faction === a.id ? 1 : 3, `/api/factions/${faction}/invites`, 'POST', { enabled: true })).invite;
    return r(user, '/api/faction-invites/' + i.url.split('=')[1] + '/accept', 'POST');
  }
  await join(2, a.id);
  await r(2, `/api/factions/${a.id}/items/Mod.Book`, 'PUT', { name: 'Book', category: 'book', quantity: 5 });
  await join(2, b.id);
  assert.deepEqual((await r(2, '/api/factions')).factions.map(f => f.id), [b.id]);
  assert.equal((await r(2, `/api/factions/${a.id}/items`)).status, 404);
  assert.equal((await r(1, `/api/factions/${a.id}/items`)).items[0].quantity, 5);
  assert.equal((await r(2, `/api/factions/${b.id}/items`)).items.length, 0);
  assert.throws(() => db.prepare("INSERT INTO faction_members VALUES (?,2,'member','now')").run(a.id), /UNIQUE/);
  const bad = await r(2, '/api/faction-invites/' + 'a'.repeat(64) + '/accept', 'POST');
  assert.equal(bad.status, 404);
  assert.equal((await r(2, '/api/factions')).factions[0].id, b.id);
});
